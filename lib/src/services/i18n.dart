  /// Translate using JSON assets (and optional DB override).
  static String tr(
    BuildContext context,
    String key, {
    String? fallback,
    Map<String, String>? params,
  }) {
    final locale = Localizations.localeOf(context).languageCode;
    return trLocale(locale, key, fallback: fallback, params: params);
  }

  /// Translate without a BuildContext (e.g., services).
  static String trLocale(
    String locale,
    String key, {
    String? fallback,
    Map<String, String>? params,
  }) {
    final normalizedLocale = _normalizeLocale(locale);
    final localizedServiceText = TranslationService.instance.translate(
      normalizedLocale,
      key,
    );
    final localizedHardFallback = _hardFallback(normalizedLocale, key);
    final frenchServiceText = TranslationService.instance.translate('fr', key);
    final frenchHardFallback = _hardFallback('fr', key);

    var text =
        localizedServiceText ??
        localizedHardFallback ??
        frenchServiceText ??
        frenchHardFallback ??
        fallback ??
        key;

    if (text == key) {
      text =
          _hardFallback(normalizedLocale, key) ??
          _hardFallback('fr', key) ??
          text;
    }

    if (_looksCorrupt(text)) {
      final hard = _hardFallback(normalizedLocale, key);
      if (hard != null && !_looksCorrupt(hard)) {
        text = hard;
      } else if (fallback != null && !_looksCorrupt(fallback)) {
        text = fallback;
      } else {
        final frValue = TranslationService.instance.translate('fr', key);
        if (frValue != null && !_looksCorrupt(frValue)) {
          text = frValue;
        }
      }
    }

    if (_looksKeyLikePlaceholder(text)) {
      final hard =
          _hardFallback(normalizedLocale, key) ?? _hardFallback('fr', key);
      if (hard != null && !_looksCorrupt(hard)) {
        text = hard;
      } else if (fallback != null &&
          !_looksCorrupt(fallback) &&
          !_looksKeyLikePlaceholder(fallback)) {
        text = fallback;
      } else {
        text = _humanizeKey(key);
      }
    }

    if (params != null && params.isNotEmpty) {
      params.forEach((k, v) {
        text = text.replaceAll('{$k}', v);
      });
    }
    return text;
  }

  static String _normalizeLocale(String locale) {
    final normalized = locale.toLowerCase();
    if (normalized == 'fr' ||
        normalized.startsWith('fr_') ||
        normalized.startsWith('fr-')) {
      return 'fr';
    }
    if (normalized == 'ar' ||
        normalized.startsWith('ar_') ||
        normalized.startsWith('ar-')) {
      return 'ar';
    }
    return 'fr';
  }

  static String? _hardFallback(String locale, String key) {
    if (locale == 'ar') return _hardFallbackAr[key];
    return _hardFallbackFr[key];
  }

  /// [key] defaults to the French text; override to use a stable key from DB.
  static String t(BuildContext context, String fr, String ar, {String? key}) {
    final localeCode = _normalizeLocale(
      Localizations.localeOf(context).toString(),
    );
    final k = key ?? fr;
    final db = TranslationService.instance.translate(localeCode, k);
    if (db != null && db.isNotEmpty && !_looksCorrupt(db)) return db;
    if (localeCode == 'ar') {
      return _looksCorrupt(ar) ? fr : ar;
    }
    return fr;
  }

  static bool _looksCorrupt(String value) {
    if (value.isEmpty) return true;
    if (_looksKeyLikePlaceholder(value)) return true;
    if (value.contains('\uFFFD') ||
        value.contains('\u00C3') ||
        value.contains('\u00C2') ||
        value.contains('\u00D8') ||
        value.contains('\u00D9')) {
      return true;
    }
    if (RegExp(r'[A-Za-z]\?[A-Za-z]').hasMatch(value)) {
      return true;
    }
    if (RegExp(r'^\?{3,}$').hasMatch(value.replaceAll(' ', ''))) {
      return true;
    }
    final questionMarks = '?'.allMatches(value).length;
    if (questionMarks >= 3 && questionMarks * 3 >= value.length) {
      return true;
    }
    for (final unit in value.codeUnits) {
      if (unit <= 0x1F || (unit >= 0x80 && unit <= 0x9F)) {
        return true;
      }
    }
    return false;
  }

  static bool _looksKeyLikePlaceholder(String value) {
    final normalized = _normalizePlaceholderCandidate(value);
    if (normalized.isEmpty) return true;
    return RegExp(r'^[a-z0-9_-]+(?:\.[a-z0-9_-]+)+$').hasMatch(normalized);
  }

  static String _normalizePlaceholderCandidate(String input) {
    return input
        .replaceAll(
          RegExp(r'[\u200B-\u200F\u202A-\u202E\u2066-\u2069\uFEFF]'),
          '',
        )
        .trim()
        .toLowerCase();
  }

  static String _humanizeKey(String key) {
    final last = key.split('.').last;
    if (last.isEmpty) return key;
    return last
        .split('_')
        .where((part) => part.isNotEmpty)
        .map((part) => '${part[0].toUpperCase()}${part.substring(1)}')
        .join(' ');
  }
